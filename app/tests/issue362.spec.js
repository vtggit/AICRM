// Hostile, user-controllable values: unescaped, the name/details/competitor
// would inject an <img> whose onerror sets window.__pwned, the reason
// category and competitor would too, and the outcome value would terminate
// the class attribute and forge an onmouseover handler.
const HOSTILE_VALUE = '<img src=x onerror=window.__pwned=1>';
const HOSTILE_OUTCOME = 'x" onmouseover="window.__pwned=1';
const LONG_DETAILS = 'D'.repeat(2000);
// A quote in the details must not terminate the title attribute and forge
// an on* handler on the row.
const QUOTED_DETAILS = 'He said "stop" and walked away.';
expect(LONG_DETAILS.length, 'the long details text is 2,000 characters').toBe(2000);

const REASON_CATS = ['budget', 'competitor', 'feature-gap', 'timing',
                     'decision-changed', 'internal-issues', 'other'];

const BASE_TS = Date.UTC(2026, 6, 1);
function isoAt(minutes) {
  return new Date(BASE_TS + minutes * 60000).toISOString();
}

// 300 outcomes: the five special rows (hostile values, the hostile outcome
// modifier, a long and a quoted details) are the newest, then 295 generated
// rows, one minute apart, so newest-first is checkable.
function makeOutcomes() {
  const special = [
    { // 300 — hostile name/details/competitor on a won outcome
      id: 'oc-h0', lead_id: 'lead-h0', lead_name: HOSTILE_VALUE,
      outcome: 'won', reason_category: 'competitor', reason_text: HOSTILE_VALUE,
      competitor_name: HOSTILE_VALUE, created_at: isoAt(300), updated_at: isoAt(300),
    },
    { // 301 — hostile outcome value: no modifier, text "Unknown"
      id: 'oc-h1', lead_id: 'lead-h1', lead_name: 'Badge Lead',
      outcome: HOSTILE_OUTCOME, reason_category: 'weird-category', reason_text: null,
      competitor_name: null, created_at: isoAt(301), updated_at: isoAt(301),
    },
    { // 302 — a plain lost outcome
      id: 'oc-h2', lead_id: 'lead-h2', lead_name: 'Lost Lead',
      outcome: 'lost', reason_category: 'timing', reason_text: 'Timing was off.',
      competitor_name: null, created_at: isoAt(302), updated_at: isoAt(302),
    },
    { // 303 — 2,000-character details: the row stays one line
      id: 'oc-h3', lead_id: 'lead-h3', lead_name: 'Long Details Lead',
      outcome: 'won', reason_category: 'budget', reason_text: LONG_DETAILS,
      competitor_name: null, created_at: isoAt(303), updated_at: isoAt(303),
    },
    { // 304 — a quote in the details: the title keeps it as data
      id: 'oc-h4', lead_id: 'lead-h4', lead_name: 'Quoted Lead',
      outcome: 'won', reason_category: 'other', reason_text: QUOTED_DETAILS,
      competitor_name: null, created_at: isoAt(304), updated_at: isoAt(304),
    },
  ];
  const out = [];
  for (let i = 1; i <= 295; i++) {
    const ts = isoAt(i);
    out.push({
      id: 'oc-' + String(i).padStart(3, '0'),
      lead_id: 'lead-' + String(i).padStart(3, '0'),
      lead_name: 'Lead ' + String(i).padStart(3, '0'),
      outcome: i % 3 === 0 ? 'lost' : 'won',
      reason_category: REASON_CATS[i % 7],
      reason_text: 'Details ' + i + '.',
      competitor_name: i % 4 === 0 ? 'RivalCorp ' + i : null,
      created_at: ts,
      updated_at: ts,
    });
  }
  return out.concat(special);
}

// 40 rows in each chart. The first win-reason row carries the hostile
// reason category AND the non-numeric count "abc"; the first loss-reason
// and competitor rows carry the hostile value.
function makeAnalytics() {
  const winReasons = [];
  const lossReasons = [];
  const competitors = [];
  for (let i = 0; i < 40; i++) {
    winReasons.push({ reason: REASON_CATS[i % 7], count: 40 - i });
    lossReasons.push({ reason: REASON_CATS[(i + 3) % 7], count: 30 - (i % 30) });
    competitors.push({ competitor: 'Rival ' + (i + 1), count: 20 - (i % 20) });
  }
  winReasons[0] = { reason: HOSTILE_VALUE, count: 'abc' };
  lossReasons[0] = { reason: HOSTILE_VALUE, count: 7 };
  competitors[0] = { competitor: HOSTILE_VALUE, count: 9 };
  return {
    total_won: 187,
    total_lost: 113,
    win_rate: 62.3,
    top_win_reasons: winReasons,
    top_loss_reasons: lossReasons,
    competitor_mentions: competitors,
  };
}

function emptyAnalytics() {
  return {
    total_won: 0,
    total_lost: 0,
    win_rate: 0,
    top_win_reasons: [],
    top_loss_reasons: [],
    competitor_mentions: [],
  };
}

/**
 * Boot the page the production way: the token is in the URL hash as
 * #access_token=..., and /api/auth/config + /api/auth/me are mocked for
 * that user. Every other API call is mocked too — no backend. Google Fonts
 * is stubbed so the run never depends on the network.
 *
 * The /deal-outcomes mock keeps an in-memory list: GET /deal-outcomes pages
 * it (limit/offset, as ApiClient.getAllPages pages) and
 * GET /deal-outcomes/analytics serves the analytics object.
 */
async function boot(page, outcomes, analytics) {
  const user = { username: 'admin-user', sub: 'u1', roles: ['admin'], display_name: 'Admin' };
  const state = { outcomes, analytics, calls: [] };
  await page.addInitScript((cfg) => { window.AICRM_CONFIG = cfg; },
    { API_BASE_URL: 'http://localhost:9000/api' });
  await page.route('**/fonts.googleapis.com/**', (route) =>
    route.fulfill({ status: 200, contentType: 'text/css', body: '' }));
  await page.route('**/fonts.gstatic.com/**', (route) =>
    route.fulfill({ status: 200, contentType: 'font/woff2', body: '' }));
  await page.route('**/api/**', (route) => {
    const req = route.request();
    const url = req.url();
    state.calls.push({ method: req.method(), url, auth: req.headers()['authorization'] || '' });
    const json = (o, status = 200) =>
      route.fulfill({
        status,
        contentType: 'application/json',
        body: JSON.stringify(o),
        // Never let the browser cache a mocked response: a cached copy
        // would bypass this route.
        headers: { 'cache-control': 'no-store' },
      });
    if (/\/auth\/me/.test(url)) {
      // Mocked for THIS user. The production boot sends the hash token as a
      // Bearer header; after the hash is cleaned, reloads may arrive without
      // one and still resolve to the same user. A foreign token does not.
      const auth = req.headers()['authorization'] || '';
      if (auth && !auth.includes(ADMIN_TOKEN)) return json({ authenticated: false, user: null });
      return json({ authenticated: true, user });
    }
    if (/\/auth\/config/.test(url)) return json({ auth_enabled: true });
    if (/\/health/.test(url)) return json({ status: 'ok', app_version: '0.2.3' });
    if (/\/deal-outcomes\/analytics(\?|&|$)/.test(url)) return json(state.analytics);
    if (/\/deal-outcomes(\?|&|$)/.test(url)) {
      if (req.method() === 'POST') {
        return json({ id: 'oc-new', ...(JSON.parse(req.postData() || '{}')) }, 201);
      }
      // Honour the limit/offset paging used by ApiClient.getAllPages.
      const u = new URL(url);
      const limit = Math.max(1, parseInt(u.searchParams.get('limit') || '100', 10) || 100);
      const offset = Math.max(0, parseInt(u.searchParams.get('offset') || '0', 10) || 0);
      return json(state.outcomes.slice(offset, offset + limit));
    }
    if (/\/contacts(\?|&|$)/.test(url)) return json([]);
    if (/\/leads(\?|&|$)/.test(url)) return json([]);
    if (/\/companies(\?|&|$)/.test(url)) return json([]);
    if (/\/activities(\?|&|$)/.test(url)) return json([]);
    if (/\/settings/.test(url)) return json({ payload: {} });
    return json([]);
  });
  await page.goto(INDEX + '#access_token=' + encodeURIComponent(ADMIN_TOKEN));
  await page.waitForFunction(
    () => typeof App !== 'undefined' && !!document.getElementById('page-title'),
    { timeout: 20000 });
  await page.waitForFunction(
    () => typeof Auth !== 'undefined' && Auth.isAuthenticated && Auth.isAuthenticated(),
    { timeout: 20000 });
  return state;
}

async function openWinLoss(page, rowCount) {
  await page.evaluate(() => { location.hash = '#/winloss'; });
  await page.waitForFunction(
    (n) => document.querySelectorAll('#winloss-table tbody tr').length === n
      && document.querySelectorAll('#win-reasons-chart .winloss-bar-row').length >= 1
      && document.querySelectorAll('#loss-reasons-chart .winloss-bar-row').length >= 1
      && document.querySelectorAll('#competitor-chart .winloss-bar-row').length >= 1,
    rowCount, { timeout: 30000 });
}

