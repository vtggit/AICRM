// Proof for issue #362 — the Win/Loss page escapes every API value and
// fits the window.
//
// In-browser proof (real Chromium; the API is fully mocked with page.route —
// no backend). The page boots the production way: the token rides the URL
// hash as #access_token=..., and /api/auth/config + /api/auth/me are mocked
// for that user.
//
//   AC-1  Every value from the API is escaped on #page-winloss.
//         • An outcome whose lead name, details and competitor name are each
//           `<img src=x onerror=window.__pwned=1>`, plus an analytics
//           competitor and a reason category carrying the same value: all
//           shown as inert text — no `img` element anywhere inside
//           #page-winloss and window.__pwned stays undefined. A hostile
//           value may appear as inert text inside an ordinary attribute's
//           value (the details title carries the full text), which is not a
//           failure.
//         • An outcome whose `outcome` is `x" onmouseover="window.__pwned=1`
//           forges no attribute whose name starts with `on` on any element
//           inside #page-winloss; its badge reads "Unknown" with no
//           modifier class, and window.__pwned stays undefined after
//           hovering it.
//         • A chart count of "abc" gives a bar of width 0 and the count
//           shown as "0" (counts are read as numbers).
//         • A won and a lost outcome show "Won" / "Lost" with the
//           outcome-won / outcome-lost modifier classes.
//
//   AC-2  The page fits the window.
//         • The three figures (Total won, Total lost, Win rate) sit in one
//           bar at the top; the three charts (Win reasons, Loss reasons,
//           Competitor mentions) sit side by side under it, each at most
//           220 px tall and scrolling inside itself when it has more rows.
//         • The outcomes table fills the rest of the height and scrolls
//           inside its own region, with its header row in view after it is
//           scrolled to its end. Each row is one line; a 2,000-character
//           details text keeps its row one line and the cell's title holds
//           the full text.
//         • At 1440x900 with 300 mocked outcomes and 40 reasons in each
//           chart, neither the document nor the content region scrolls —
//           only the table region and the charts do. At 900 px and below
//           the charts stack and the page scrolls vertically, and
//           390x844 has no horizontal page scroll.
//         • Unchanged: the figures and how they are worked out, the
//           newest-first order, the date format, the empty-state texts
//           (no outcomes, no analytics), every element id and the win/loss
//           reason form. Styles live in css/winloss.css, tokens only.

