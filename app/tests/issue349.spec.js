// Issue #349 — the sidebar footer shows the application version and the
// signed-in user is shown by name.
//
// In-browser proof (real Chromium; the API is fully mocked with page.route —
// no backend). The page boots the production way: the token rides the URL
// hash as #access_token=..., and /api/auth/config + /api/auth/me are mocked
// for that user.
//
//   AC-1  the sidebar footer (#app-version-sidebar) reads "v" followed by
//         the app_version from GET /api/health — "v9.8.7" when the mocked
//         route answers app_version "9.8.7" — and #app-version-settings on
//         the Settings page reads the same version without the "v". While
//         the request is out (the mocked route delays it) the footer shows
//         nothing, never "loading", and reads "v9.8.7" once it answers.
//         When the request answers 500 the footer still shows nothing, the
//         Settings page reads "unavailable", and no page error is raised.
//         The request goes through ApiClient: a GET /api/health call on
//         the wire carries the client's Content-Type header AND the Bearer
//         Authorization header that ApiClient injects — a bare fetch()
//         carries neither, so Content-Type alone is not proof of the client.
//
//   AC-2  the footer chip (#auth-status .auth-username), its title, the
//         footer's "Logged in as" title and the "Welcome" notification after
//         signing in show the first of display_name, username, email, sub
//         that is not empty: with username "pat.planner" plus email and sub
//         and no display_name the chip reads "pat.planner" (and so does its
//         title); with only email and sub it reads the email; with only sub
//         it reads the sub; with a display_name it reads the display_name.
//         A username of <img src=x onerror=window.__pwned=1> renders as
//         inert text with window.__pwned undefined, and a 120-character
//         username is cut with an ellipsis inside the sidebar's width while
//         the full name stays in the title.
//
// Identity: the "(viewer)" test boots the page the production way for a
// NON-ADMIN (role 'user') and asserts the admin-only control is absent
// while the page still renders, including across a full reload.

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

const path = require('path');

const INDEX = 'file://' + path.resolve(__dirname, '..', 'index.html');
const ADMIN_TOKEN = 'dev-secret-token:admin';
const VIEWER_TOKEN = 'dev-secret-token:user';

// The hostile username from the AC: unescaped, it would inject an <img>
// whose onerror handler sets window.__pwned.
const XSS_USERNAME = '<img src=x onerror=window.__pwned=1>';
// A 120-character username (the AC's long-name case).
const LONG_USERNAME = 'Longhand '.repeat(15).slice(0, 120);

// Per-pass mocked API state. The route handler reads this on every request,
// so a pass changes behaviour by mutating it and re-booting the page.
const state = {
  user: null,            // the /api/auth/me user for this pass
  requireAuth: false,    // true => /api/auth/me needs the Bearer token
  healthStatus: 200,     // status the mocked GET /api/health answers with
  healthBody: { status: 'ok', app_version: '9.8.7' },
  healthDelayMs: 0,      // latency applied INSIDE the mocked route
  contacts: [],
};

function makeContacts(n) {
  const out = [];
  for (let i = 1; i <= n; i += 1) {
    out.push({
      id: 'c-' + String(i).padStart(3, '0'),
      name: 'Contact ' + String(i).padStart(3, '0'),
      email: 'contact' + i + '@example.com',
      phone: null,
      company: i % 2 === 0 ? 'Acme Corp' : null,
      status: 'active',
      notes: null,
      tags: [],
      created_at: '2026-01-01T08:00:00Z',
      updated_at: '2026-01-01T08:00:00Z',
    });
  }
  return out;
}

/**
 * Boot the page the production way: the token is in the URL hash as
 * #access_token=... (unless withToken is false — the signed-out login
 * pass), and /api/auth/config + /api/auth/me are mocked for the current
 * `state`. Every other API call is mocked too — no backend. Google Fonts
 * is stubbed so the run never depends on the network.
 *
 * Every boot loads a FRESH document. After the first boot,
 * Auth._migrateTokenFromHash() strips the hash via history.replaceState,
 * so a plain page.goto() to the same INDEX+hash would be a same-document
 * (fragment) navigation: the app's scripts would not re-run and the
 * previous pass's APP_VERSION / auth state would survive. Navigating
 * through about:blank forces a full document load, and the unique
 * &boot=N fragment guarantees a URL the browser has never visited.
 *
 * initScripts are addInitScript callbacks (e.g. clearing the stored
 * token for the signed-out pass); they run before the page's own scripts
 * on every boot navigation. Playwright offers no API to unregister an
 * init script, so they stay registered for the rest of the test's page;
 * each Playwright test gets a fresh browser context, so nothing leaks
 * across tests, and the only current user (the signed-out pass) is the
 * last boot of its test — its guard keeps it inert for token boots.
 *
 * Returns the recorded API calls (method, url, authorization header,
 * content-type header).
 */
let bootSeq = 0;
async function boot(page, token, withToken = true, initScripts = []) {
  const calls = [];
  await page.unrouteAll({ behavior: 'ignore' });
  await page.route('**/fonts.googleapis.com/**', (route) =>
    route.fulfill({ status: 200, contentType: 'text/css', body: '' }));
  await page.route('**/fonts.gstatic.com/**', (route) =>
    route.fulfill({ status: 200, contentType: 'font/woff2', body: '' }));
  await page.route('**/api/**', (route) => {
    const req = route.request();
    const url = req.url();
    calls.push({
      method: req.method(),
      url,
      auth: req.headers()['authorization'] || '',
      contentType: req.headers()['content-type'] || '',
    });
    const json = (status, body) =>
      route.fulfill({
        status,
        contentType: 'application/json',
        body: JSON.stringify(body),
        // Never let the browser cache a mocked response: a cached copy
        // would bypass this route (and any delay inside it) on a later
        // pass.
        headers: { 'cache-control': 'no-store' },
      });
    if (/\/auth\/me/.test(url)) {
      const auth = req.headers()['authorization'] || '';
      const foreign = state.requireAuth
        ? auth !== 'Bearer ' + token
        : (auth && !auth.includes(token));
      if (foreign || !state.user) return json(200, { authenticated: false, user: null });
      return json(200, { authenticated: true, user: state.user });
    }
    if (/\/auth\/config/.test(url)) {
      return json(200, { authEnabled: true, authMode: 'development' });
    }
    if (/\/health/.test(url)) {
      if (state.healthDelayMs > 0) {
        // The delay is made in the mocked route, not with a fixed wait on
        // the page: the response is held for healthDelayMs before it lands.
        return new Promise((resolve) => {
          setTimeout(() => resolve(json(state.healthStatus, state.healthBody)), state.healthDelayMs);
        });
      }
      return json(state.healthStatus, state.healthBody);
    }
    if (/\/settings/.test(url)) return json(200, { payload: {} });
    if (/\/contacts(\b|\?|$)/.test(url)) {
      // Honour the limit/offset paging used by ApiClient.getAllPages.
      const u = new URL(url);
      const limit = Math.max(1, parseInt(u.searchParams.get('limit') || '100', 10) || 100);
      const offset = Math.max(0, parseInt(u.searchParams.get('offset') || '0', 10) || 0);
      return json(200, state.contacts.slice(offset, offset + limit));
    }
    return json(200, []);
  });

  bootSeq += 1;
  for (const fn of initScripts) await page.addInitScript(fn);
  // about:blank first: the opaque-origin detour makes the app
  // navigation a full document load, never a same-document fragment
  // no-op (see the note above).
  await page.goto('about:blank');
  const hash = withToken
    ? '#access_token=' + encodeURIComponent(token) + '&boot=' + bootSeq
    : '#boot=' + bootSeq;
  await page.goto(INDEX + hash, { waitUntil: 'load' });
  await page.waitForFunction(
    () => typeof App !== 'undefined' && !!document.getElementById('page-title'),
    { timeout: 20000 });
  if (withToken) {
    // Auth state resolved to signed-in (the green indicator is written
    // by _updateAuthStatus only after Auth.init() settled).
    await page.waitForFunction(
      () => {
        const el = document.querySelector('#auth-status .auth-indicator');
        return el && el.textContent === '🟢';
      },
      { timeout: 20000 });
    await page.waitForFunction(
      () => typeof Auth !== 'undefined' && Auth.isAuthenticated && Auth.isAuthenticated(),
      { timeout: 20000 });
  } else {
    // Auth state resolved to signed-out.
    await page.waitForFunction(
      () => {
        const el = document.querySelector('#auth-status .auth-indicator');
        return el && el.textContent === '🔴';
      },
      { timeout: 20000 });
  }
  return calls;
}

/** Boot a signed-in pass with the given /api/auth/me user. */
async function bootSignedIn(page, token, user) {
  state.user = user;
  state.requireAuth = false;
  return boot(page, token);
}

test('issue349 freeform', async ({ page }) => {
  test.setTimeout(180000);
  const pageErrors = [];
  page.on('pageerror', (e) => pageErrors.push(String(e)));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.addInitScript((cfg) => { window.AICRM_CONFIG = cfg; },
    { API_BASE_URL: 'http://localhost:9000/api' });

  const sidebarVersion = page.locator('#app-version-sidebar');
  const settingsVersion = page.locator('#app-version-settings');
  const chip = page.locator('#auth-status .auth-username');
  const authStatus = page.locator('#auth-status');

  // ── AC-1: health answers app_version "9.8.7" ────────────────────────────
  // /api/auth/me: username + email + sub, NO display_name (AC-2 case 1).
  const calls = await bootSignedIn(page, ADMIN_TOKEN, {
    sub: 'sub-777',
    username: 'pat.planner',
    email: 'pat.planner@example.com',
    roles: ['admin'],
  });
  // Production boot: the hash token was sent as the Bearer header.
  await expect.poll(
    () => calls.some((c) => /\/auth\/me/.test(c.url) && c.auth === 'Bearer ' + ADMIN_TOKEN),
    { timeout: 10000 }).toBe(true);

  await expect(sidebarVersion).toHaveText('v9.8.7', { timeout: 10000 });
  await expect(settingsVersion).toHaveText('9.8.7');
  // The version request went through ApiClient: _headers() stamps the
  // Content-Type header on every request AND injects the Authorization
  // header via Auth.getAuthorizationHeader() — a bare fetch() carries
  // neither, so Content-Type alone would not prove the client. Startup
  // issues two /api/health calls (the availability check and the version
  // fetch); the availability check is guaranteed to carry the full header
  // set, and the footer text above shows the version came from this
  // endpoint's mocked response.
  const healthCall = calls.find(
    (c) => /\/health(\?|$)/.test(c.url) && c.method === 'GET'
      && c.auth === 'Bearer ' + ADMIN_TOKEN);
  expect(healthCall,
    'a /api/health call carrying the Bearer token ApiClient injects').toBeTruthy();
  expect(healthCall.contentType,
    'that /api/health call also carries the ApiClient Content-Type header')
    .toBe('application/json');
  // The Settings page itself reads the bare version.
  await page.evaluate(() => { location.hash = '#/settings'; });
  await expect(page.locator('#page-settings.active')).toBeVisible();
  await expect(settingsVersion).toBeVisible();
  await expect(settingsVersion).toHaveText('9.8.7');

  // ── AC-2 (case 1): username "pat.planner" (no display_name) ─────────────
  await expect(chip).toHaveText('pat.planner');
  expect(await chip.getAttribute('title'), 'chip title keeps the name').toBe('pat.planner');
  expect(await authStatus.getAttribute('title'),
    'footer title reads "Logged in as <name>"').toBe('Logged in as pat.planner');

  // ── AC-1: the request is delayed IN THE MOCKED ROUTE ────────────────────
  // Wide margin: boot() returns as soon as auth settles (two fast mocked
  // calls), so the in-flight window is the delay minus ~a few hundred ms.
  state.healthDelayMs = 5000;
  await bootSignedIn(page, ADMIN_TOKEN, {
    sub: 'sub-777', username: 'pat.planner', email: 'pat.planner@example.com', roles: ['admin'],
  });
  // While the request is out the footer shows nothing — and, sampled
  // continuously until it resolves, never contains "loading".
  expect((await sidebarVersion.textContent()) || '',
    'footer is empty while the request is out').toBe('');
  let sawLoading = false;
  await expect.poll(async () => {
    const text = (await sidebarVersion.textContent()) || '';
    if (text.toLowerCase().includes('loading')) sawLoading = true;
    return text;
  }, { timeout: 15000, intervals: [50] }).toBe('v9.8.7');
  expect(sawLoading, 'footer never contains "loading"').toBe(false);
  await expect(settingsVersion).toHaveText('9.8.7');

  // ── AC-1: the request answers 500 ───────────────────────────────────────
  state.healthDelayMs = 0;
  state.healthStatus = 500;
  state.healthBody = { detail: 'Internal Server Error' };
  await bootSignedIn(page, ADMIN_TOKEN, {
    sub: 'sub-777', username: 'pat.planner', email: 'pat.planner@example.com', roles: ['admin'],
  });
  await expect(settingsVersion).toHaveText('unavailable', { timeout: 10000 });
  expect((await sidebarVersion.textContent()) || '',
    'footer stays empty on a failed request').toBe('');
  await page.evaluate(() => { location.hash = '#/settings'; });
  await expect(page.locator('#page-settings.active')).toBeVisible();
  await expect(settingsVersion).toBeVisible();
  await expect(settingsVersion).toHaveText('unavailable');

  // ── AC-1: a NUMERIC app_version of 0 is a real version, not "missing" ───
  state.healthStatus = 200;
  state.healthBody = { status: 'ok', app_version: 0 };
  await bootSignedIn(page, ADMIN_TOKEN, {
    sub: 'sub-777', username: 'pat.planner', email: 'pat.planner@example.com', roles: ['admin'],
  });
  await expect(sidebarVersion).toHaveText('v0', { timeout: 10000 });
  await expect(settingsVersion).toHaveText('0');
  await page.evaluate(() => { location.hash = '#/settings'; });
  await expect(page.locator('#page-settings.active')).toBeVisible();
  await expect(settingsVersion).toBeVisible();
  await expect(settingsVersion).toHaveText('0');

  // ── AC-2 (case 2): only email and sub → the email ───────────────────────
  state.healthStatus = 200;
  state.healthBody = { status: 'ok', app_version: '9.8.7' };
  await bootSignedIn(page, ADMIN_TOKEN, {
    sub: 'sub-777', email: 'only.email@example.com', roles: ['admin'],
  });
  await expect(chip).toHaveText('only.email@example.com');
  expect(await chip.getAttribute('title')).toBe('only.email@example.com');
  expect(await authStatus.getAttribute('title'))
    .toBe('Logged in as only.email@example.com');

  // ── AC-2 (case 3): only sub → the sub ───────────────────────────────────
  await bootSignedIn(page, ADMIN_TOKEN, { sub: 'sub-777', roles: ['admin'] });
  await expect(chip).toHaveText('sub-777');
  expect(await chip.getAttribute('title')).toBe('sub-777');

  // ── AC-2 (case 4): a display_name wins over everything ──────────────────
  await bootSignedIn(page, ADMIN_TOKEN, {
    sub: 'sub-777',
    username: 'pat.planner',
    email: 'pat.planner@example.com',
    display_name: 'Pat Planner',
    roles: ['admin'],
  });
  await expect(chip).toHaveText('Pat Planner');
  expect(await chip.getAttribute('title')).toBe('Pat Planner');
  expect(await authStatus.getAttribute('title')).toBe('Logged in as Pat Planner');

  // ── AC-2 (case 5): hostile username renders as inert text ───────────────
  await bootSignedIn(page, ADMIN_TOKEN, { sub: 'sub-777', username: XSS_USERNAME, roles: ['admin'] });
  await expect(chip).toHaveText(XSS_USERNAME);
  expect(await page.locator('#auth-status img').count(),
    'the hostile username must not create an <img> element').toBe(0);
  expect(await page.evaluate(() => window.__pwned),
    'window.__pwned must stay undefined').toBeUndefined();
  expect(await chip.getAttribute('title'), 'full name stays in the title').toBe(XSS_USERNAME);

  // ── AC-2 (case 6): a 120-character username stays inside the sidebar ────
  await bootSignedIn(page, ADMIN_TOKEN, { sub: 'sub-777', username: LONG_USERNAME, roles: ['admin'] });
  await expect(chip).toHaveText(LONG_USERNAME);
  expect(await chip.getAttribute('title'), 'the full long name stays in the title')
    .toBe(LONG_USERNAME);
  const geometry = await page.evaluate(() => {
    const nameEl = document.querySelector('#auth-status .auth-username');
    const chipEl = document.querySelector('#sidebar .sidebar-footer #auth-status');
    const sidebarEl = document.querySelector('#sidebar');
    const nameRect = nameEl.getBoundingClientRect();
    const chipRect = chipEl.getBoundingClientRect();
    const sidebarRect = sidebarEl.getBoundingClientRect();
    return {
      clipped: nameEl.scrollWidth > nameEl.clientWidth,
      textOverflow: getComputedStyle(nameEl).textOverflow,
      nameWidth: nameRect.width,
      chipLeft: chipRect.left,
      chipRight: chipRect.right,
      sidebarLeft: sidebarRect.left,
      sidebarRight: sidebarRect.right,
    };
  });
  expect(geometry.textOverflow, 'the long name is cut with an ellipsis').toBe('ellipsis');
  expect(geometry.clipped, 'the name is actually clipped, not wrapped').toBe(true);
  expect(geometry.chipLeft, 'the chip stays inside the sidebar (left)')
    .toBeGreaterThanOrEqual(geometry.sidebarLeft - 1);
  expect(geometry.chipRight, 'the chip stays inside the sidebar (right)')
    .toBeLessThanOrEqual(geometry.sidebarRight + 1);

  // ── AC-2: the "Welcome" notification after signing in ───────────────────
  // Boot signed OUT (no hash token; the mocked /api/auth/me then demands the
  // Bearer token) and sign in through the login modal.
  state.requireAuth = true;
  state.user = {
    sub: 'sub-777', username: 'pat.planner', email: 'pat.planner@example.com', roles: ['admin'],
  };
  // Previous passes left the admin token in sessionStorage; without
  // clearing it the signed-out boot would auto-authenticate and the
  // login flow would never appear.
  // Self-scoping: it only clears the stored token when the URL carries
  // no #access_token=... (i.e. on the signed-out boot). Because the
  // init script stays registered on the page, the guard keeps it inert
  // for any token-carrying boot that might follow.
  const clearStoredToken = () => {
    try {
      if (!/access_token=/.test(window.location.hash)) {
        sessionStorage.removeItem('aicrm_token');
      }
    } catch { /* opaque origin */ }
  };
  const signedOutCalls = await boot(page, ADMIN_TOKEN, false, [clearStoredToken]);
  expect(signedOutCalls.some((c) => /\/auth\/me/.test(c.url) && c.auth === ''),
    'the signed-out boot calls /api/auth/me without a Bearer token').toBe(true);
  await page.click('#auth-status');
  await page.fill('#login-token', ADMIN_TOKEN);
  await page.click('#login-submit');
  const welcome = page.locator('.notification', { hasText: 'Welcome, pat.planner' });
  await expect(welcome, 'the Welcome notification shows the name').toBeVisible();
  await expect(welcome).toHaveText('Welcome, pat.planner');
  await expect(chip).toHaveText('pat.planner');

  expect(pageErrors, `page errors: ${pageErrors.join(' | ')}`).toEqual([]);
});

test('issue349 freeform (viewer)', async ({ page }) => {
  test.setTimeout(90000);
  const pageErrors = [];
  page.on('pageerror', (e) => pageErrors.push(String(e)));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.addInitScript((cfg) => { window.AICRM_CONFIG = cfg; },
    { API_BASE_URL: 'http://localhost:9000/api' });

  // Identity: the same production boot, but NON-ADMIN (role 'user').
  state.healthStatus = 200;
  state.healthBody = { status: 'ok', app_version: '9.8.7' };
  state.healthDelayMs = 0;
  state.requireAuth = false;
  state.contacts = makeContacts(3);
  const calls = await bootSignedIn(page, VIEWER_TOKEN, {
    sub: 'sub-777', username: 'pat.planner', email: 'pat.planner@example.com', roles: ['user'],
  });
  const roles = await page.evaluate(() => (Auth.getCurrentUser() || {}).roles);
  expect(roles, 'the viewer pass runs as a NON-ADMIN (role "user")').toEqual(['user']);
  await expect.poll(
    () => calls.some((c) => /\/auth\/me/.test(c.url) && c.auth === 'Bearer ' + VIEWER_TOKEN),
    { timeout: 10000 }).toBe(true);

  // The page still renders: shell, dashboard content, the version footer
  // and the signed-in user by name.
  await expect(page.locator('#page-dashboard.active')).toBeVisible();
  await expect(page.locator('#page-title')).toHaveText('Dashboard');
  await expect(page.locator('#app-version-sidebar')).toHaveText('v9.8.7');
  await expect(page.locator('#auth-status .auth-username')).toHaveText('pat.planner');

  // The admin-only control is absent for the viewer — on the Contacts page
  // itself, where an admin would see "+ Add Contact".
  await page.evaluate(() => { location.hash = '#/contacts'; });
  await page.waitForFunction(
    () => document.querySelectorAll('#contacts-list .contact-card').length === 3,
    { timeout: 20000 });
  await expect(page.locator('#page-title')).toHaveText('Contacts');
  await expect(page.locator('#btn-add-contact')).toBeHidden();
  const adminOnlyVisible = await page.evaluate(() =>
    Array.from(document.querySelectorAll('[data-admin-only="true"]'))
      .filter((el) => el.offsetParent !== null)
      .map((el) => el.id || el.className));
  expect(adminOnlyVisible, 'no admin-only control may be visible to a non-admin')
    .toEqual([]);

  // A full reload keeps the viewer role, reopens the hash route, and the
  // admin-only control stays absent while the page still renders.
  await page.reload();
  await page.waitForFunction(
    () => Auth.isAuthenticated && Auth.isAuthenticated(),
    { timeout: 20000 });
  expect(await page.evaluate(() => (Auth.getCurrentUser() || {}).roles)).toEqual(['user']);
  await page.waitForFunction(
    () => document.querySelectorAll('#contacts-list .contact-card').length === 3,
    { timeout: 20000 });
  await expect(page.locator('#page-contacts.active')).toBeVisible();
  await expect(page.locator('#page-title')).toHaveText('Contacts');
  await expect(page.locator('#app-version-sidebar')).toHaveText('v9.8.7');
  await expect(page.locator('#auth-status .auth-username')).toHaveText('pat.planner');
  await expect(page.locator('#btn-add-contact')).toBeHidden();

  expect(pageErrors, `page errors: ${pageErrors.join(' | ')}`).toEqual([]);
});
