// 40 funnel steps: counts descend 400 → 1 (so step 0 is the 100 % bar and
// the tail sits on the 15 % floor the page has always used). The first
// label is the wide word; the rest are ordinary.
function makeWideFunnel() {
  const steps = [];
  for (let i = 0; i < 40; i++) {
    const count = 400 - i * 10;
    steps.push({
      stage: 'stage-' + (i + 1),
      label: i === 0 ? WIDE_LABEL : 'Stage ' + String(i + 1).padStart(2, '0'),
      count,
      value: count * 100,
      conversion_rate: i === 0 ? 100 : Math.round((count / (count + 10)) * 1000) / 10,
      drop_off: i === 0 ? 0 : 10,
      avg_days_in_stage: i % 3 === 2 ? null : 1.5 + i / 10,
    });
  }
  return {
    total_leads: 500,
    lost_leads: 50,
    won_leads: 40,
    overall_conversion_rate: 8,
    total_pipeline_value: 1234567.89,
    won_value: 4000000,
    funnel_steps: steps,
    generated_at: new Date().toISOString(),
  };
}

