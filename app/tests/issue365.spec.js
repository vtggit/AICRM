// API value, reads every figure as a number, and fits the window.
//
// In-browser proof (real Chromium; the API is fully mocked with page.route —
// no backend). The page boots the production way: the token rides the URL
// hash as #access_token=..., and /api/auth/config + /api/auth/me are mocked
// for that user.
//
//   AC-1  app.js fixes the two trend defects and hardens the figures.
//         • Bound once: Analytics is shown five times (each showing of the
//           page re-binds the trend controls) and then #trend-range is
//           changed once — exactly one trend request is sent.
//         • Newest answer wins: two trend choices are made quickly with the
//           first answered last — the second choice's data is drawn (each
//           trend request carries a sequence number; an answer for an older
//           request is dropped).
//         • Escaped: a funnel step whose label is
//           `<img src=x onerror=window.__pwned=1>` is shown as inert text in
//           both the funnel chart and the stage table — no img element
//           inside #page-analytics, no attribute whose name starts with
//           `on`, and window.__pwned stays undefined.
//         • Numbers are read as numbers: a step with a count of "abc" and
//           no value shows 0 (count) and $0 (value), its bar keeps a valid
//           width, and the page throws no error.
//         • Figures: a response with no total_pipeline_value shows "$0.00"
//           and the missing count figures show 0.
//   AC-2  The Analytics page fits the window.
//         • The four figures sit in one bar at the top; the funnel chart
//           and the stage table sit side by side under it, each scrolling
//           inside itself when it has more rows than fit.
//         • At 1440x900 with 40 mocked funnel steps, neither the document
//           nor the content region scrolls — the funnel and the table each
