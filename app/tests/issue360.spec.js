// What the progress endpoint answers. g-fallback is deliberately missing
// (the row must fall back to the goal's own current value), and g-pg-full's
// endpoint value reaches its target even though the goal's own value and
// stored progress_percent are 0.
const PROGRESS_SET = MAIN_SET
  .filter((g) => g.id !== 'g-fallback')
  .map((g) => (g.id === 'g-pg-full'
    ? { ...g, current_value: g.target_value, progress_percent: 100 }
    : g));

// Today's percentage rule, mirrored for the expectations: the progress
// endpoint's current value for the goal (else the goal's own), over the
// target, rounded, at most 100, 0 when the target is 0.
function expectedPctFor(goal, progressById) {
  const pg = progressById[goal.id];
  const current = (pg ? pg.current_value : 0) || goal.current_value || 0;
  if (!(goal.target_value > 0)) return 0;
  return Math.min(100, Math.round((current / goal.target_value) * 100));
}

function makeManyGoals(n) {
  const types = ['revenue', 'deals', 'contacts', 'activities'];
  const periods = ['monthly', 'quarterly', 'yearly'];
  const out = [];
  for (let i = 1; i <= n; i++) {
    const day = ((i - 1) % 28) + 1;
    out.push(makeGoal({
      id: 'g-' + String(i).padStart(3, '0'),
      name: 'Goal ' + String(i).padStart(3, '0'),
      type: types[i % 4],
      target_value: 100 + i,
      current_value: Math.floor(i / 2),
      period: periods[i % 3],
      start_date: '2026-10-' + String(day).padStart(2, '0'),
      end_date: '2026-11-' + String(day).padStart(2, '0'),
      progress_percent: 0,
    }));
  }
  return out;
}

/**
 * Boot the page the production way: the token is in the URL hash as
 * #access_token=..., and /api/auth/config + /api/auth/me are mocked for
 * that user. Every other API call is mocked too — no backend. Google Fonts
 * is stubbed so the run never depends on the network.
 *
 * The /sales-goals mock keeps an in-memory list: GET /sales-goals/{id},
 * PATCH /sales-goals/{id} and DELETE /sales-goals/{id} mutate it, and the
 * paged GET serves it. A later boot registers a newer route, which takes
 * precedence (LIFO), so each boot sees exactly its own data.
 *
 * Returns the mock state (goals, progress, recorded calls).
 */
// startToken may be null: the boot then starts signed out (no token in the
// URL hash and none in sessionStorage), and the sales-goals mock answers
// 401 to every request until a login supplies the token.
async function boot(page, startToken, goals, progress) {
  const user = { username: 'admin-user', sub: 'u1', roles: ['admin'], display_name: 'Admin' };
  const state = {
    token: ADMIN_TOKEN,
    goals: goals.map((g) => ({ ...g })),
    progress: progress.map((g) => ({ ...g })),
    calls: [],
  };
  await page.route('**/api/**', (route) => {
    const req = route.request();
    const url = req.url();
    state.calls.push({ method: req.method(), url, body: req.postData() });
    const json = (o, status = 200) =>
      route.fulfill({
        status,
        contentType: 'application/json',
        body: JSON.stringify(o),
        // Never let the browser cache a mocked response: a cached copy
        // would bypass this route (and any later boot's data).
        headers: { 'cache-control': 'no-store' },
      });
    if (/\/auth\/me/.test(url)) {
      // Mocked for THIS user. The production boot sends the hash token as a
      // Bearer header; a request without the token does not authenticate.
      const auth = req.headers()['authorization'] || '';
      if (auth.includes(state.token)) return json({ authenticated: true, user });
      return json({ authenticated: false, user: null });
    }
    if (/\/auth\/config/.test(url)) return json({ auth_enabled: true });
    if (/\/health/.test(url)) return json({ status: 'ok', app_version: '0.2.3' });
    // The sales-goals API is auth-protected: without the token it answers
    // 401, so a signed-out boot cannot render its goals until a login
    // supplies the token.
    if (/\/sales-goals/.test(url)
      && !(req.headers()['authorization'] || '').includes(state.token)) {
      return json({ detail: 'Not authenticated.' }, 401);
    }

    if (/\/sales-goals\/progress(\?|&|$)/.test(url)) {
      return json({ goals: state.progress, overall_progress: 0 });
    }
    if (/\/sales-goals\/recalculate(\?|&|$)/.test(url)) {
      return json(state.goals);
    }
    const writeMatch = url.match(/\/sales-goals\/([^?#]+)$/);
    if (writeMatch) {
      const id = decodeURIComponent(writeMatch[1]);
      const idx = state.goals.findIndex((g) => String(g.id) === id);
      if (req.method() === 'GET') {
        if (idx === -1) return json({ detail: 'Sales goal not found.' }, 404);
        return json(state.goals[idx]);
      }
      if (req.method() === 'PATCH') {
        if (idx === -1) return json({ detail: 'Sales goal not found.' }, 404);
        const patch = JSON.parse(req.postData() || '{}');
        const mapped = {};
        if (patch.name !== undefined) mapped.name = patch.name;
        if (patch.target_value !== undefined) mapped.target_value = patch.target_value;
        if (patch.start_date !== undefined) mapped.start_date = patch.start_date;
        if (patch.end_date !== undefined) mapped.end_date = patch.end_date;
        state.goals[idx] = { ...state.goals[idx], ...mapped };
        return json(state.goals[idx]);
      }
      if (req.method() === 'DELETE') {
        if (idx === -1) return json({ detail: 'Sales goal not found.' }, 404);
        state.goals = state.goals.filter((g) => String(g.id) !== id);
        state.progress = state.progress.filter((g) => String(g.id) !== id);
        return route.fulfill({ status: 204, headers: { 'cache-control': 'no-store' } });
      }
    }
    if (req.method() === 'POST' && /\/sales-goals(\?|&|$)/.test(url)) {
      const body = JSON.parse(req.postData() || '{}');
      const goal = makeGoal({ id: 'g-new-' + (state.goals.length + 1), ...body });
      state.goals = [...state.goals, goal];
      return json(goal, 201);
    }
    if (/\/sales-goals(\?|&|$)/.test(url)) {
      // Honour the limit/offset paging used by ApiClient.getAllPages.
      const u = new URL(url);
      const limit = Math.max(1, parseInt(u.searchParams.get('limit') || String(state.goals.length), 10) || state.goals.length);
      const offset = Math.max(0, parseInt(u.searchParams.get('offset') || '0', 10) || 0);
      return json(state.goals.slice(offset, offset + limit));
    }
    if (/\/contacts(\?|&|$)/.test(url)) return json([]);
    if (/\/leads(\?|&|$)/.test(url)) return json([]);
    if (/\/activities(\?|&|$)/.test(url)) return json([]);
    if (/\/companies(\?|&|$)/.test(url)) return json([]);
    if (/\/settings/.test(url)) return json({ payload: {} });
    return json([]);
  });
  await page.setViewportSize({ width: 1440, height: 900 });
  // A fresh document per boot: a plain page.goto() to the same INDEX+hash
  // would be a same-document (fragment) navigation, and the app's in-memory
  // state would leak from the previous boot. The clock and the routes
  // survive the navigation; the init scripts are re-applied on the fresh load.
  await page.goto('about:blank');
  if (startToken === null) {
    // Signed-out boot: drop the token a previous boot left in sessionStorage
    // so the app really starts unauthenticated.
    await page.addInitScript(() => {
      try { sessionStorage.removeItem('aicrm_token'); } catch (e) { /* no-op */ }
    });
    await page.goto(INDEX, { waitUntil: 'load' });
    // Settle in the signed-out state (the chip carries the unauth title).
    await page.waitForFunction(
      () => typeof App !== 'undefined' && typeof Auth !== 'undefined'
        && Auth._initialized && !Auth.isAuthenticated()
        && document.getElementById('auth-status').title === 'Not authenticated \u2014 click to log in',
      { polling: 100, timeout: 20000 });
  } else {
    await page.goto(INDEX + '#access_token=' + encodeURIComponent(startToken), { waitUntil: 'load' });
    await page.waitForFunction(
      () => typeof App !== 'undefined' && typeof Auth !== 'undefined'
        && Auth.isAuthenticated && Auth.isAuthenticated(),
      { polling: 100, timeout: 20000 });
  }
  return state;
}

/** Open the Sales Goals page (hash route) and wait for the rows. */
async function openSalesGoals(page, rowCount) {
  await page.evaluate(() => { location.hash = '#/salesgoals'; });
  await page.waitForFunction(
    (count) => document.getElementById('page-salesgoals').classList.contains('active')
      && document.querySelectorAll('#goals-list .goal-card').length === count,
    rowCount,
    { polling: 100, timeout: 30000 });
}

