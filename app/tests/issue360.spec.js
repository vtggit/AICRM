  await expect(page.locator('#goal-name')).toHaveValue('');
  await expect(page.locator('#goal-type')).toHaveValue('revenue');
  await expect(page.locator('#goal-period')).toHaveValue('quarterly');
  await expect(page.locator('#goal-start')).toHaveValue('2026-10-14');
  await expect(page.locator('#goal-end')).toHaveValue('');
  await page.locator('#btn-cancel-goal').click();
  await expect(page.locator('#modal-overlay')).toHaveClass(/hidden/);

  // ══════════════════════════════════════════════════════════════════════
  // Boot 4 — signed-out boot: the Sales Goals page re-renders once the
  // login succeeds (renderCurrentPage covers salesgoals)
  // ══════════════════════════════════════════════════════════════════════
  const unauthState = await boot(page, null, MAIN_SET, PROGRESS_SET);
  await openSalesGoals(page, 0);
  // The signed-out render attempt hits the API and is rejected with 401;
