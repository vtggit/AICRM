// Proof for issue #360 — the Sales Goals page (#page-salesgoals) fits the
// window.
//
// In-browser proof (real Chromium; the API is fully mocked with page.route —
// no backend). The page boots the production way: the token rides the URL
// hash as #access_token=..., and /api/auth/config + /api/auth/me are mocked
// for that user. The clock is fixed by Playwright's clock (page.clock) at
// 2026-10-14 12:00 UTC, so "days left" and the active-goal filter are
// deterministic.
//
//   AC-1  Summary and toolbar: one bar above the list holds the three
//         summary figures (#goal-overall-progress, #goal-active-count,
//         #goal-completed-count, each with its label and without its emoji
//         icon) and #btn-recalculate-goals reading "Recalculate" plus
//         #btn-add-goal reading "Add goal" — no emoji, no "+".
//         List (#goals-list): one compact row per goal (>= 52 px) keeping
//         the class goal-card and its data-id, showing in order the type
//         badge (.goal-type-badge), the name (.goal-name), the progress bar
//         with its percentage (.goal-progress-fill, .goal-progress-pct),
//         the current and target values (.goal-progress-values), the period,
//         the date range, the days left (.goal-days-left) and the Edit and
//         Delete buttons. Every field the card showed is still shown,
//         without emoji: the .goal-completed-badge reads "Completed", and
//         the days left read "N days left", "1 day left" or "Ended" once the
//         end date has passed. A long name is cut with an ellipsis on one
//         line and its title carries the full name. Edit/Delete keep their
//         classes and data-id and carry accessible names "Edit goal" /
//         "Delete goal".
//         One rule for "completed": a goal is completed when the percentage
//         its row shows is at least 100, and #goal-completed-count is the
//         number of rows showing the badge. The row's percentage keeps
//         today's rule: the progress endpoint's current value for that goal
//         (else the goal's own) over its target, rounded, at most 100, 0
//         when the target is 0.
//         Type is escaped: a hostile type gets no modifier class, its label
//         is still shown, and nothing executes. A hostile name renders as
//         text. A 300-character name at 1440x900 keeps the row one line and
//         >= 52 px tall, the buttons stay inside the row, and the title
//         carries the full name. With 300 goals at 1440x900 neither the
//         document nor the content region scrolls — only #goals-list does.
//         At 900 px and below the period and the date range are hidden and
//         390x844 has no horizontal page scroll. With no goals a centred
//         empty state reads "No sales goals yet." with an "Add goal" beside
//         or below it. The modal, create/update/delete/recalculate with
//         their notifications, the start-date order and the overall-progress
//         / active-count rules are unchanged.
//         Defect proofs: a 300-character type is capped by the badge's
//         max-width and clipped (no row overflow), and the Sales Goals
//         page re-renders after a successful login on that page.

