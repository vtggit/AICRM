// 300 activities: 270 spread over October 2026 (the 15th left alone) plus
// 30 that all land on the 15th, so that one day cell overflows. Every fifth
// scattered activity is due on its own day — the early-month ones are
// overdue at the fixed clock; the first of them (id act-000, due 2026-10-01)
// must sort first in the timeline.
function makeMany() {
  const types = ['call', 'email', 'meeting', 'note', 'task'];
  const out = [];
  for (let i = 0; i < 270; i++) {
    const d = i % 29; // 0..28 -> days 1..14 then 16..30 (the 15th stays free)
    const day = d < 14 ? d + 1 : d + 2;
    out.push({
      id: 'act-' + String(i).padStart(3, '0'),
      type: types[i % 5],
      description: 'Activity ' + i,
      contact_name: i % 3 === 0 ? 'Contact ' + i : null,
      occurred_at: '2026-10-' + String(day).padStart(2, '0') + 'T' + String(8 + (i % 12)).padStart(2, '0') + ':00:00Z',
      due_date: i % 5 === 0 ? '2026-10-' + String(day).padStart(2, '0') + 'T09:00:00Z' : null,
      status: i % 7 === 3 ? 'completed' : 'pending',
    });
  }
  for (let i = 0; i < 30; i++) {
    out.push({
      id: 'burst-' + i,
      type: types[i % 5],
      description: 'Burst event ' + i,
      contact_name: null,
      occurred_at: '2026-10-15T12:00:00Z',
      due_date: null,
      status: 'pending',
    });
  }
  return out;
}

/**
 * Boot the page the production way: the token is in the URL hash as
 * #access_token=..., and /api/auth/config + /api/auth/me are mocked for
 * that user. Every other API call is mocked too — no backend. Google Fonts
 * is stubbed so the run never depends on the network.
 *
 * The /activities mock keeps an in-memory list: PUT /activities/{id} patches
 * it, DELETE /activities/{id} removes from it, and the paged GET serves it.
 * A later boot registers a newer route, which takes precedence (LIFO), so
 * each boot sees exactly its own data.
 *
 * Returns the mock state (activities list + recorded calls).
 */
async function boot(page, token, activities) {
  const user = { username: 'admin-user', sub: 'u1', roles: ['admin'], display_name: 'Admin' };
  const state = {
    token,
    activities: activities.map((a) => ({ ...a })),
    calls: [],
  };
  await page.route('**/api/**', (route) => {
    const req = route.request();
    const url = req.url();
    state.calls.push({ method: req.method(), url, body: req.postData() });
    const json = (o, status = 200) =>
      route.fulfill({
        status,
        contentType: 'application/json',
        body: JSON.stringify(o),
        // Never let the browser cache a mocked response: a cached copy
        // would bypass this route (and any later boot's data).
        headers: { 'cache-control': 'no-store' },
      });
    if (/\/auth\/me/.test(url)) {
      // Mocked for THIS user. The production boot sends the hash token as a
      // Bearer header; a foreign token does not authenticate.
      const auth = req.headers()['authorization'] || '';
      if (auth && !auth.includes(state.token)) return json({ authenticated: false, user: null });
      return json({ authenticated: true, user });
    }
    if (/\/auth\/config/.test(url)) return json({ auth_enabled: true });
    if (/\/health/.test(url)) return json({ status: 'ok', app_version: '0.2.3' });
    const writeMatch = url.match(/\/activities\/([^?#]+)$/);
    if (writeMatch) {
      const id = decodeURIComponent(writeMatch[1]);
      if (req.method() === 'PUT') {
        const idx = state.activities.findIndex((a) => String(a.id) === id);
        if (idx === -1) return json({ detail: 'Not found' }, 404);
        const patch = JSON.parse(req.postData() || '{}');
        state.activities[idx] = { ...state.activities[idx], ...patch };
        return json(state.activities[idx]);
      }
      if (req.method() === 'DELETE') {
        state.activities = state.activities.filter((a) => String(a.id) !== id);
        return route.fulfill({ status: 204 });
      }
    }
    if (/\/activities(\?|&|$)/.test(url)) {
      // Honour the limit/offset paging used by ApiClient.getAllPages.
      const u = new URL(url);
      const limit = Math.max(1, parseInt(u.searchParams.get('limit') || String(state.activities.length), 10) || state.activities.length);
      const offset = Math.max(0, parseInt(u.searchParams.get('offset') || '0', 10) || 0);
      return json(state.activities.slice(offset, offset + limit));
    }
    if (/\/contacts(\?|&|$)/.test(url)) return json([]);
    if (/\/leads(\?|&|$)/.test(url)) return json([]);
    if (/\/companies(\?|&|$)/.test(url)) return json([]);
    if (/\/settings/.test(url)) return json({ payload: {} });
    return json([]);
  });
  await page.setViewportSize({ width: 1440, height: 900 });
  // A fresh document per boot: a plain page.goto() to the same INDEX+hash
  // would be a same-document (fragment) navigation, and the app's in-memory
  // state (notably the calendar-view flag) would leak from the previous boot.
  // The clock and the routes survive the navigation; the init scripts and
  // the sessionStorage token are re-applied on the fresh load.
  await page.goto('about:blank');
  await page.goto(INDEX + '#access_token=' + encodeURIComponent(token), { waitUntil: 'load' });
  await page.waitForFunction(
    () => typeof App !== 'undefined' && typeof Auth !== 'undefined'
      && Auth.isAuthenticated && Auth.isAuthenticated(),
    { polling: 100, timeout: 20000 });
  return state;
}

/** The page's clock must still read the fixed test day. */
async function expectFixedDay(page) {
  const day = await page.evaluate(() => new Date().toISOString().slice(0, 10));
  expect(day, 'the Playwright clock keeps the proof on 2026-10-14').toBe('2026-10-14');
}

/** Open the Activities page (hash route) and wait for it to be active. */
async function openActivities(page, rowCount) {
  await page.evaluate(() => { location.hash = '#/activities'; });
  if (rowCount != null) {
    await page.waitForFunction(
      (count) => document.getElementById('page-activities').classList.contains('active')
        && document.querySelectorAll('#activities-list .timeline-item').length === count,
      rowCount,
      { polling: 100, timeout: 30000 });
  } else {
    await page.waitForFunction(
      () => document.getElementById('page-activities').classList.contains('active'),
      { polling: 100, timeout: 30000 });
  }
}

function hexToRgb(hex) {
  const h = hex.replace('#', '');
  return 'rgb(' + [0, 2, 4].map((o) => parseInt(h.slice(o, o + 2), 16)).join(', ') + ')';
}

