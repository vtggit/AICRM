/**
 * Boot the page the production way: the token is in the URL hash as
 * #access_token=..., and /api/auth/config + /api/auth/me are mocked for
 * that user. Every other API call is mocked too — no backend. Google Fonts
 * is stubbed so the run never depends on the network.
 *
 * Returns the mock state (recorded calls).
 */
async function boot(page, contacts, leads) {
  const user = { username: 'admin-user', sub: 'u1', roles: ['admin'], display_name: 'Admin' };
  const state = { contacts, leads, calls: [] };
  await page.route('**/api/**', (route) => {
    const req = route.request();
    const url = req.url();
    state.calls.push({ method: req.method(), url });
    if (req.method() === 'OPTIONS') {
      // CORS preflight: the page boots from file://, so the browser asks
      // permission before sending the real cross-origin request that
      // carries its Authorization header.
      return route.fulfill({
        status: 204,
        headers: {
          'access-control-allow-origin': '*',
          'access-control-allow-methods': 'GET, POST, PUT, PATCH, DELETE, OPTIONS',
          'access-control-allow-headers': 'content-type, authorization',
          'access-control-max-age': '600',
          'cache-control': 'no-store',
        },
      });
    }
    const json = (o) =>
      route.fulfill({
        status: 200,
        contentType: 'application/json',
        body: JSON.stringify(o),
        // CORS: the page boots from file://, so every mocked response is
        // cross-origin and must carry the allow-origin header, or the
        // browser blocks the body before the app can read it.
        headers: {
          'access-control-allow-origin': '*',
          // Never let the browser cache a mocked response: a cached copy
          // would bypass this route.
          'cache-control': 'no-store',
        },
      });
    if (/\/auth\/me/.test(url)) {
      // Mocked for THIS user. The production boot sends the hash token as a
      // Bearer header; a request without the token does not authenticate.
      const auth = req.headers()['authorization'] || '';
      if (auth && auth.includes(ADMIN_TOKEN)) {
        return json({ authenticated: true, user });
      }
      return json({ authenticated: false, user: null });
    }
    if (/\/auth\/config/.test(url)) return json({ auth_enabled: true });
    if (/\/health/.test(url)) return json({ status: 'ok', app_version: '0.2.3' });
    if (/\/analytics\/activity-trends/.test(url)) return json(makeTrend());
    if (/\/suppressions\/may-send/.test(url)) {
      const email = new URL(url).searchParams.get('email') || '';
      return json({ email, may_send: false, reasons: [] });
    }
    if (/\/contacts(\?|&|$)/.test(url)) return json(state.contacts);
    if (/\/leads(\?|&|$)/.test(url)) return json(state.leads);
    if (/\/activities(\?|&|$)/.test(url)) return json([]);
    if (/\/tags(\?|&|$)/.test(url)) return json([]);
    if (/\/settings/.test(url)) return json({ payload: {} });
    return json([]);
  });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(INDEX + '#access_token=' + encodeURIComponent(ADMIN_TOKEN), { waitUntil: 'load' });
  await page.waitForFunction(
    () => typeof App !== 'undefined' && typeof Auth !== 'undefined'
      && Auth._initialized && Auth.isAuthenticated(),
    { polling: 100, timeout: 20000 });
  return state;
}

/**
 * Type a query into #global-search and let the 300 ms debounce fire. The
 * fixed clock makes the debounce wait exact: runFor(400) fires the
 * handler's single timer and nothing else pending at 300 ms or less.
 */
async function typeSearch(page, query) {
  await page.evaluate((q) => {
    const input = document.getElementById('global-search');
    input.value = q;
    input.dispatchEvent(new Event('input', { bubbles: true }));
  }, query);
  await page.clock.runFor(400);
}

test('issue368 freeform', async ({ page }) => {
  test.setTimeout(240000);
  const pageErrors = [];
  page.on('pageerror', (e) => pageErrors.push(String(e)));
  page.on('dialog', (d) => d.accept());

  // Fix the clock BEFORE any page script runs: every new Date() the page
  // makes (the relative times, the dashboard stats) is then deterministic,
  // whatever day the test happens to run.
  await page.clock.install({ time: new Date(FIXED_NOW), timeZone: 'UTC' });

  // One-time page setup: the config init script and the font stubs.
  await page.addInitScript((cfg) => { window.AICRM_CONFIG = cfg; },
    { API_BASE_URL: 'http://localhost:9000/api' });
  await page.route('**/fonts.googleapis.com/**', (route) =>
    route.fulfill({ status: 200, contentType: 'text/css', body: '' }));
  await page.route('**/fonts.gstatic.com/**', (route) =>
    route.fulfill({ status: 200, contentType: 'font/woff2', body: '' }));

  const state = await boot(page, CONTACTS, LEADS);
  expect(state.calls.length, 'the boot talked to the mocked API').toBeGreaterThan(0);

  const day = await page.evaluate(() => new Date().toISOString().slice(0, 10));
  expect(day, 'the Playwright clock keeps the proof on 2026-10-15').toBe('2026-10-15');

  // The boot lands on the dashboard; wait for its recent contacts (all four
  // — the list keeps at most five) and its trend overview to render.
  await page.waitForFunction(
    () => document.querySelectorAll('#recent-contacts .recent-item').length === 4
      && (document.getElementById('activity-trend-overview').textContent || '')
        .includes('Total Activities'),
    { polling: 100, timeout: 30000 });

  // ══════════════════════════════════════════════════════════════════════
  // AC-3 — readable times only, on the Dashboard at boot
  // ══════════════════════════════════════════════════════════════════════

  // The contact whose created_at is "not a date" is in the recent list;
  // nothing on the page may carry "NaN".
  const docText = await page.evaluate(() => document.documentElement.textContent || '');
  expect(docText, 'no "NaN" anywhere on the page').not.toContain('NaN');

  const times = await page.evaluate(() => {
    const out = {};
    document.querySelectorAll('#recent-contacts .recent-item').forEach((el) => {
      const timeEl = el.querySelector('.recent-item-time');
      out[el.getAttribute('data-contact-id')] = timeEl ? timeEl.textContent.trim() : null;
    });
    return out;
  });
  expect(times['c-nameless'], 'the unreadable date has no relative time').toBe('');
  expect(times['c-ada'], 'five minutes before the fixed clock').toBe('5m ago');
  expect(times['c-grace'], 'three hours before the fixed clock').toBe('3h ago');
  expect(times['c-turing'], 'ten days before the fixed clock').toBe('1w ago');

  // ══════════════════════════════════════════════════════════════════════
  // AC-1 — no crash: one contact has name: null; "ada" still matches Ada
  // ══════════════════════════════════════════════════════════════════════
  await typeSearch(page, 'ada');
  await page.waitForFunction(
    () => document.getElementById('page-contacts').classList.contains('active')
      && document.querySelectorAll('#contacts-list .contact-card').length === 1,
    { polling: 100, timeout: 30000 });
  const adaNames = await page.evaluate(() =>
    Array.from(document.querySelectorAll('#contacts-list .contact-card h4'))
      .map((el) => el.textContent.trim()));
  expect(adaNames, 'the search lands on the contacts page showing Ada')
    .toEqual(['Ada Lovelace']);
  expect(pageErrors, 'the null-name contact never stopped the search').toEqual([]);

  // ══════════════════════════════════════════════════════════════════════
  // AC-2 — no match: "zzzz" notifies with the query as text and the
  //        "ada"-filtered contacts list re-renders with every contact
  // ══════════════════════════════════════════════════════════════════════
  await typeSearch(page, 'zzzz');
  await page.waitForFunction(
    () => Array.from(document.querySelectorAll('#notification-container .notification'))
      .some((n) => n.textContent === 'No contacts or leads match "zzzz".'),
    { polling: 100, timeout: 30000 });
  await page.waitForFunction(
    () => document.querySelectorAll('#contacts-list .contact-card').length === 4,
    { polling: 100, timeout: 30000 });
  const allNames = await page.evaluate(() =>
    Array.from(document.querySelectorAll('#contacts-list .contact-card h4'))
      .map((el) => el.textContent.trim())
      .sort());
  expect(allNames, 'the list that "ada" had filtered shows every contact again')
    .toEqual(['', 'Ada Lovelace', 'Alan Turing', 'Grace Hopper']);

  // ══════════════════════════════════════════════════════════════════════
  // AC-1 — no crash / leads: one lead has no name field; the company
  //        search lands on the leads page with the matched lead
  // ══════════════════════════════════════════════════════════════════════
  await typeSearch(page, 'zephyr');
  await page.waitForFunction(
    () => document.getElementById('page-leads').classList.contains('active')
      && document.querySelectorAll('#leads-list .lead-card').length === 1,
    { polling: 100, timeout: 30000 });
  const leadNames = await page.evaluate(() =>
    Array.from(document.querySelectorAll('#leads-list .lead-row-name'))
      .map((el) => el.textContent.trim()));
  expect(leadNames, 'the leads page shows the lead matched by company')
    .toEqual(['Morgan Lee']);
  expect(pageErrors, 'the nameless lead never stopped the search').toEqual([]);

  // ══════════════════════════════════════════════════════════════════════
  // AC-2 — hostile query matches nothing: the notification shows it as
  //        text, nothing executes, and the "zephyr"-filtered leads list
  //        re-renders unfiltered
  // ══════════════════════════════════════════════════════════════════════
  await typeSearch(page, HOSTILE_QUERY);
  await page.waitForFunction((hostile) =>
    Array.from(document.querySelectorAll('#notification-container .notification'))
      .some((n) => n.textContent === `No contacts or leads match "${hostile}".`),
    HOSTILE_QUERY,
    { polling: 100, timeout: 30000 });
  const hostile = await page.evaluate(() => {
    const onAttrs = [];
    document.querySelectorAll('#notification-container *').forEach((el) => {
      Array.from(el.attributes).forEach((attr) => {
        if (/^on/i.test(attr.name)) onAttrs.push(el.tagName + ':' + attr.name);
      });
    });
    return {
      pwned: typeof window.__pwned,
      imgs: document.querySelectorAll('#notification-container img').length,
      onAttrs,
    };
  });
  expect(hostile.pwned, 'window.__pwned stays undefined').toBe('undefined');
  expect(hostile.imgs, 'no img element inside the notification container').toBe(0);
  expect(hostile.onAttrs, 'no attribute whose name starts with "on"').toEqual([]);
  await page.waitForFunction(
    () => document.querySelectorAll('#leads-list .lead-card').length === 3,
    { polling: 100, timeout: 30000 });

  // The whole proof ran without a single uncaught page error.
  expect(pageErrors, 'no page error during the whole proof').toEqual([]);
});
