// Proof for issue #368 — the global search tolerates records with missing
// or non-string fields, and the relative times stay readable.
//
// In-browser proof (real Chromium; the API is fully mocked with page.route —
// no backend). The page boots the production way: the token rides the URL
// hash as #access_token=..., and /api/auth/config + /api/auth/me are mocked
// for that user. The clock is fixed by Playwright's clock (page.clock) at
// 2026-10-15 12:00 UTC, so every relative time is deterministic.
//
//   AC-1  No crash: one contact has name: null and one lead has no name
//         field at all. A search for "ada" lands on the contacts page
//         showing Ada Lovelace — the null-name record is treated as empty
//         text, never a throw, and the other records still match. A search
//         that matches the other lead by company (Zephyr Analytics) lands
//         on the leads page with that lead. Neither search raises a page
//         error.
//   AC-2  No match: a search for "zzzz" matches no contact and no lead —
//         showNotification carries `No contacts or leads match "zzzz".`,
//         and the contacts list that an earlier "ada" search had filtered
//         re-renders with every contact again. A query of
//         `<img src=x onerror=window.__pwned=1>` that matches nothing is
//         shown by the notification as inert text: no img element is
//         created, no on* attribute appears, and window.__pwned stays
//         undefined.
//   AC-3  Readable times only: getRelativeTime returns the empty string
//         for a value that is not a readable date, never text containing
//         "NaN". The Dashboard's recent contacts therefore carry no "NaN"
//         anywhere on the page for a contact whose created_at is
//         "not a date". A date in the future reads "Just now", as today;
//         dates 5 minutes, 3 hours and 10 days before the fixed clock
//         read "5m ago", "3h ago" and "1w ago".
//   AC-4  Unchanged: which records a search matches when their fields are
//         present (the "ada" and "zephyr" searches match exactly their
//         records), the navigation to contacts or leads on a match, and
//         the relative-time wording for readable dates.

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

