//
// In-browser proof (real Chromium; the API is fully mocked with page.route —
// no backend). The page boots the production way: the token rides the URL
// hash as #access_token=..., and /api/auth/config + /api/auth/me are mocked
// for that user.
//
//   AC-1  tokens.css loads and holds the family token set from
//         docs/design/design-system.md (IBM Plex Sans/Mono from Google
//         Fonts); --color-sidebar resolves to #16212C; the sidebar is
//         --sidebar-width (232 px) wide and painted with --color-sidebar;
//         the nav labels are plain text in order, without emoji, with the
//         .nav-icon elements retained but glyph-free; #auth-status sits at
