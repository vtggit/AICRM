// 300 templates with distinct created_at stamps, cycling through the six
// known categories.
function makeMany(n) {
  const cats = ['follow-up', 'introduction', 'proposal', 'thank-you', 'meeting', 'other'];
  const out = [];
  for (let i = 1; i <= n; i++) {
    const day = String((i % 28) + 1).padStart(2, '0');
    const hour = String(i % 24).padStart(2, '0');
    out.push({
      id: 'tpl-' + String(i).padStart(3, '0'),
      name: 'Template ' + String(i).padStart(3, '0'),
      category: cats[i % 6],
      subject: i % 3 === 0 ? null : 'Subject ' + i,
      content: 'Body ' + i + ' from {{contact_name}}.',
      created_at: '2026-10-' + day + 'T' + hour + ':00:00Z',
      updated_at: '2026-10-' + day + 'T' + hour + ':00:00Z',
    });
  }
  return out;
}

/**
 * Boot the page the production way: the token is in the URL hash as
 * #access_token=..., and /api/auth/config + /api/auth/me are mocked for
 * that user. Every other API call is mocked too — no backend. Google Fonts
 * is stubbed so the run never depends on the network.
 *
 * The /templates mock keeps an in-memory list: DELETE /templates/{id}
 * removes from it and the paged GET serves it (limit/offset, as
 * ApiClient.getAllPages pages). opts.templateError makes GET /templates
 * fail with a 500 carrying that detail message.
 *
 * Returns the mock state (templates list + recorded calls).
 */
async function boot(page, token, templates, opts = {}) {
  const user = token === VIEWER_TOKEN
    ? { username: 'plain-user', sub: 'u1', roles: ['user'], display_name: 'Viewer One' }
    : { username: 'admin-user', sub: 'u1', roles: ['admin'], display_name: 'Admin' };
  const state = {
    token,
    templates: templates.map((t) => ({ ...t })),
    calls: [],
  };
  await page.addInitScript((cfg) => { window.AICRM_CONFIG = cfg; },
    { API_BASE_URL: 'http://localhost:9000/api' });
  await page.route('**/fonts.googleapis.com/**', (route) =>
    route.fulfill({ status: 200, contentType: 'text/css', body: '' }));
  await page.route('**/fonts.gstatic.com/**', (route) =>
    route.fulfill({ status: 200, contentType: 'font/woff2', body: '' }));
  await page.route('**/api/**', (route) => {
    const req = route.request();
    const url = req.url();
    state.calls.push({ method: req.method(), url, auth: req.headers()['authorization'] || '', body: req.postData() });
    const json = (o, status = 200) =>
      route.fulfill({
        status,
        contentType: 'application/json',
        body: JSON.stringify(o),
        // Never let the browser cache a mocked response: a cached copy
        // would bypass this route.
        headers: { 'cache-control': 'no-store' },
      });
    if (/\/auth\/me/.test(url)) {
      // Mocked for THIS user. The production boot sends the hash token as a
      // Bearer header; after the hash is cleaned, reloads may arrive without
      // one (sessionStorage token) and still resolve to the same user.
      const auth = req.headers()['authorization'] || '';
      if (auth && !auth.includes(state.token)) return json({ authenticated: false, user: null });
      return json({ authenticated: true, user });
    }
    if (/\/auth\/config/.test(url)) return json({ auth_enabled: true });
    if (/\/health/.test(url)) return json({ status: 'ok', app_version: '0.2.3' });
    const writeMatch = url.match(/\/templates\/([^?#]+)$/);
    if (writeMatch) {
      const id = decodeURIComponent(writeMatch[1]);
      if (req.method() === 'DELETE') {
        state.templates = state.templates.filter((t) => String(t.id) !== id);
        return route.fulfill({ status: 204 });
      }
      if (req.method() === 'PUT') {
        const idx = state.templates.findIndex((t) => String(t.id) === id);
        if (idx === -1) return json({ detail: 'Template not found' }, 404);
        state.templates[idx] = { ...state.templates[idx], ...JSON.parse(req.postData() || '{}') };
        return json(state.templates[idx]);
      }
    }
    if (/\/templates(\?|&|$)/.test(url)) {
      if (opts.templateError && req.method() === 'GET') {
        return json({ detail: opts.templateError }, 500);
      }
      // Honour the limit/offset paging used by ApiClient.getAllPages.
      const u = new URL(url);
      const limit = Math.max(1, parseInt(u.searchParams.get('limit') || '100', 10) || 100);
      const offset = Math.max(0, parseInt(u.searchParams.get('offset') || '0', 10) || 0);
      return json(state.templates.slice(offset, offset + limit));
    }
    if (/\/contacts(\?|&|$)/.test(url)) return json(opts.contacts || []);
    if (/\/leads(\?|&|$)/.test(url)) return json(opts.leads || []);
    if (/\/companies(\?|&|$)/.test(url)) return json([]);
    if (/\/settings/.test(url)) return json({ payload: {} });
    return json([]);
  });
  await page.goto(INDEX + '#access_token=' + encodeURIComponent(token));
  await page.waitForFunction(
    () => typeof App !== 'undefined' && !!document.getElementById('page-title'),
    { timeout: 20000 });
  await page.waitForFunction(
    () => typeof Auth !== 'undefined' && Auth.isAuthenticated && Auth.isAuthenticated(),
    { timeout: 20000 });
  return state;
}

